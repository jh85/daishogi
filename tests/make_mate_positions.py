#!/usr/bin/env python3
"""Writes tests/data/mate_positions.txt for tests/mate_test: positions from
the last plies of self-play games that ended by royal capture, where short
forced mates are common.

Usage: make_mate_positions.py GAMES_DIR [GAMES_DIR ...] [--binary ./daishogi]
       [--per-game 10] [--max-games 200]
"""

import argparse
import json
import random
import subprocess
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", nargs="+")
    ap.add_argument("--binary", default="./daishogi")
    ap.add_argument("--per-game", type=int, default=10)
    ap.add_argument("--max-games", type=int, default=200)
    ap.add_argument("--out", default="tests/data/mate_positions.txt")
    a = ap.parse_args()
    files = sorted(f for d in a.dirs for f in Path(d).rglob("game_*.json"))
    random.Random(1).shuffle(files)
    eng = subprocess.Popen([a.binary, "batch"], stdin=subprocess.PIPE,
                           stdout=subprocess.PIPE, text=True)
    out, games = [], 0
    for f in files:
        rec = json.loads(f.read_text())
        if rec["reason"] != "royals":
            continue
        moves = rec["moves"]
        for back in range(1, a.per_game + 1):
            if back > len(moves):
                break
            prefix = moves[:len(moves) - back]
            eng.stdin.write(f"position sfen {rec['initial']}"
                            + (" moves " + " ".join(prefix) if prefix else "") + "\nsfen\n")
            eng.stdin.flush()
            out.append(eng.stdout.readline().split(" ", 1)[1].strip())
        games += 1
        if games >= a.max_games:
            break
    Path(a.out).write_text(
        "# Positions 1-%d plies before the end of %d self-play games lost by royal\n"
        "# capture (generated by tests/make_mate_positions.py).\n" % (a.per_game, games)
        + "\n".join(out) + "\n")
    print(f"{len(out)} positions from {games} games -> {a.out}")


if __name__ == "__main__":
    main()
